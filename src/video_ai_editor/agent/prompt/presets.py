Aspect = Literal["9:16", "16:9", "1:1", "4:5", "other"]


# --------------------------------------------------------------------------
# 1. Safe zones
# --------------------------------------------------------------------------

@dataclass(frozen=True)
class SafeZone:
    """Fractions of the canvas. Text anchors (block centres) must satisfy
    `y_min ≤ y ≤ y_max` and `x ≤ x_max`; `caption_y` / `lower_third_y` are the
    product defaults the §4.9 handlers place captions and lower thirds at."""
    y_min: float
    y_max: float
    x_max: float
    caption_y: float
    lower_third_y: float

    def contains(self, x_frac: float, y_frac: float) -> bool:
        return self.y_min <= y_frac <= self.y_max and x_frac <= self.x_max


SAFE_ZONES: dict[str, SafeZone] = {
    # TikTok/Reels/Shorts UI: caption/handle/actions cover the bottom ~20 %
    # and the like/comment rail the right ~15 %.
    "9:16": SafeZone(y_min=0.10, y_max=0.78, x_max=0.85, caption_y=0.76, lower_third_y=0.74),
    "1:1": SafeZone(y_min=0.08, y_max=0.90, x_max=1.0, caption_y=0.85, lower_third_y=0.80),
    "4:5": SafeZone(y_min=0.08, y_max=0.90, x_max=1.0, caption_y=0.85, lower_third_y=0.80),
    "16:9": SafeZone(y_min=0.05, y_max=0.92, x_max=1.0, caption_y=0.85, lower_third_y=0.80),
}

#: Roles that live in the margin by design and are exempt from the zone.
SAFE_ZONE_EXEMPT_ROLES: frozenset[str] = frozenset({"watermark"})

#: Canvas dimensions per aspect (mirrors dispatch.auto_reframe's table).
ASPECT_DIMS: dict[str, tuple[int, int]] = {
    "9:16": (1080, 1920), "16:9": (1920, 1080), "1:1": (1080, 1080), "4:5": (1080, 1350),
}


def aspect_of(w: int | float, h: int | float, *, tol: float = 0.02) -> Aspect:
    """Classify a w×h into the four named aspects, or "other". 2 % tolerance
    so 1080×1350 (0.8) and 1088×1360 both read as 4:5."""
    if not w or not h:
        return "other"
    r = float(w) / float(h)
    for name, (aw, ah) in ASPECT_DIMS.items():
        if abs(r - aw / ah) <= tol * (aw / ah):
            return name  # type: ignore[return-value]
    return "other"


def safe_zone_for(aspect: str) -> SafeZone:
    """The zone for an aspect; unknown/"other" canvases use the 16:9 zone,
    the most permissive one, because no platform chrome is known for them."""
    return SAFE_ZONES.get(aspect, SAFE_ZONES["16:9"])


