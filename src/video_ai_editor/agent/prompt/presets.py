# 3. Fonts / LUTs / templates the validator whitelists against
# --------------------------------------------------------------------------

def font_names() -> frozenset[str]:
    """Basenames AND stems of `fonts/*.ttf` — `add_text.font` is written as a
    stem ("Inter-Black") by every existing caller and `_font_path` joins it
    to FONTS_DIR verbatim, so both spellings are the same bundled file."""
    d = Path(config.FONTS_DIR)
    if not d.is_dir():
        return frozenset()
    names: set[str] = set()
    for p in d.glob("*.ttf"):
        names.add(p.name)
        names.add(p.stem)
    return frozenset(names)


def lut_names() -> frozenset[str]:
    """Bare `.cube` basenames in presets/luts — the only form a plan may pass
    to `apply_lut` (§1.3 rule 6)."""
    d = presets_dir() / "luts"
    if not d.is_dir():
        return frozenset()
    return frozenset(p.name for p in d.glob("*.cube"))


def show_template_names() -> frozenset[str]:
    d = presets_dir() / "shows"
    if not d.is_dir():
        return frozenset()
    return frozenset(p.stem for p in d.glob("*.json"))


