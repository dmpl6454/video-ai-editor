@dataclass(frozen=True)
class EditTemplate:
    name: str
    description: str
    platform: str | None
    recipes: tuple[tuple[str, dict[str, Any]], ...]   # ordered (recipe, slots)
    keywords: tuple[str, ...] = ()
    exclusions: tuple[str, ...] = ()


def edit_templates() -> dict[str, EditTemplate]:
    """`presets/templates/*.json`. Recipe names are validated against the
    recipe table lazily (recipes.py imports this module, so the check imports
    it the other way only inside the function)."""
    from .recipes import RECIPE_SLOTS
    out: dict[str, EditTemplate] = {}
    for stem, data in _read_json_files("templates").items():
        entries: list[tuple[str, dict[str, Any]]] = []
        for item in data.get("recipes") or []:
            if isinstance(item, str):
                name, slots = item, {}
            else:
                name, slots = str(item.get("recipe")), dict(item.get("slots") or {})
            if name not in RECIPE_SLOTS:
                raise ValueError(f"template {stem}: unknown recipe {name!r}")
            unknown = set(slots) - set(RECIPE_SLOTS[name])
            if unknown:
                raise ValueError(f"template {stem}: recipe {name} has unknown slots {sorted(unknown)}")
            entries.append((name, slots))
        if not entries:
            raise ValueError(f"template {stem}: no recipes")
        out[stem] = EditTemplate(
            name=stem, description=str(data.get("description", "")),
            platform=data.get("platform"), recipes=tuple(entries),
            keywords=tuple(str(k).lower() for k in (data.get("keywords") or [])),
            exclusions=tuple(str(k) for k in (data.get("exclusions") or [])),
        )
    return out


