BED_DURATION_S = 180.0
BED_SAMPLE_RATE = 48000
BED_TARGET_LUFS = -18.0

#: (name, bpm, mood). Names are stable: the `music` recipe, K's benchmark
#: fixture and the .gitignore pattern all refer to them.
BED_SPECS: tuple[tuple[str, int, str], ...] = (
    ("chill_90bpm", 90, "chill"),
    ("upbeat_120bpm", 120, "upbeat"),
    ("cinematic_70bpm", 70, "cinematic"),
    ("lofi_85bpm", 85, "lofi"),
)
MOODS: tuple[str, ...] = tuple(m for _, _, m in BED_SPECS)


@dataclass(frozen=True)
class MusicBed:
    name: str
    path: Path
    bpm: float
    mood: str
    beat_grid_offset: float = 0.0
    duration_s: float = BED_DURATION_S
    source: str = "procedural"

    @property
    def period(self) -> float:
        return 60.0 / self.bpm

    def beats(self, until: float) -> list[float]:
        """Exact beat instants from the grid, in bed-local seconds, < `until`."""
        n = int(math.floor((until - self.beat_grid_offset) / self.period)) + 1
        return [round(self.beat_grid_offset + i * self.period, 6) for i in range(max(0, n))
                if self.beat_grid_offset + i * self.period < until]


def music_beds(directory: Path | None = None) -> list[MusicBed]:
    """Beds whose .wav AND .json sidecar exist; `[]` when none were generated.
    Never raises for a missing directory (see module docstring)."""
    d = Path(directory) if directory is not None else music_dir()
    if not d.is_dir():
        return []
    out: list[MusicBed] = []
    for sidecar in sorted(d.glob("*.json")):
        wav = sidecar.with_suffix(".wav")
        if not wav.exists():
            continue
        try:
            meta = json.loads(sidecar.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        try:
            out.append(MusicBed(
                name=sidecar.stem, path=wav.resolve(), bpm=float(meta["bpm"]),
                mood=str(meta.get("mood", sidecar.stem.split("_")[0])),
                beat_grid_offset=float(meta.get("beat_grid_offset", 0.0)),
                duration_s=float(meta.get("duration_s", BED_DURATION_S)),
                source=str(meta.get("source", "procedural")),
            ))
        except (KeyError, TypeError, ValueError):
            continue
    return out


def bed_for_mood(mood: str | None, directory: Path | None = None) -> MusicBed | None:
    beds = music_beds(directory)
    if not beds:
        return None
    if mood:
        for b in beds:
            if b.mood == mood:
                return b
    return next((b for b in beds if b.mood == "chill"), beds[0])


def _bed_expression(bpm: int, mood: str) -> str:
    """A deterministic lavfi `aevalsrc` expression: a kick exactly on the beat
    grid (t = k·60/bpm), a lighter click on the off-beats, and a slow pad.
    Written so librosa's beat tracker and the sidecar grid agree: the kick is
    the loudest transient by a wide margin and nothing else is periodic at a
    competing rate."""
    p = 60.0 / bpm
    ph = f"(t-floor(t/{p:.6f})*{p:.6f})"          # seconds since the last beat
    half = f"(t+{p / 2:.6f}-floor((t+{p / 2:.6f})/{p:.6f})*{p:.6f})"  # since the last off-beat
    # The beat carries BOTH the kick and the sharpest transient. A first
    # version put the only click on the off-beats and librosa locked onto it
    # (detected beats sat at 0.766, 1.277 … on a 120 BPM grid: the off-beats),
    # which would have made every "split lands on a detected beat" check
    # disagree with the sidecar grid by half a period.
    kick = f"0.9*sin(2*PI*(52+40*exp(-{ph}*30))*{ph})*exp(-{ph}*11)"
    snap = f"0.4*sin(2*PI*2600*t)*exp(-{ph}*120)"
    click = f"0.08*sin(2*PI*3200*t)*exp(-{half}*90)"
    pads = {
        "chill": "0.06*(sin(2*PI*220*t)+sin(2*PI*277.18*t)+sin(2*PI*329.63*t))*(0.6+0.4*sin(2*PI*0.08*t))",
        "upbeat": "0.06*(sin(2*PI*261.63*t)+sin(2*PI*329.63*t)+sin(2*PI*392*t))*(0.7+0.3*sin(2*PI*0.25*t))",
        "cinematic": "0.07*(sin(2*PI*110*t)+sin(2*PI*164.81*t)+sin(2*PI*196*t))*(0.5+0.5*sin(2*PI*0.05*t))",
        "lofi": "0.05*(sin(2*PI*196*t)+sin(2*PI*246.94*t)+sin(2*PI*293.66*t))*(0.6+0.4*sin(2*PI*0.12*t))",
    }[mood]
    return f"{kick}+{snap}+{click}+{pads}"


_LUFS_RE = re.compile(r"I:\s*(-?[\d.]+)\s*LUFS")


def _measure_lufs(path: Path) -> float:
    proc = subprocess.run(
        [_pu.FFMPEG, "-hide_banner", "-nostats", "-i", str(path),
         "-af", "ebur128=peak=none", "-f", "null", "-"],
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        **_pu.SUBPROCESS_FLAGS)
    hits = _LUFS_RE.findall(proc.stderr)
    if not hits:
        raise RuntimeError(f"ebur128 gave no integrated loudness for {path}: {proc.stderr[-400:]}")
    return float(hits[-1])


def _run_ffmpeg(args: list[str]) -> None:
    proc = subprocess.run([_pu.FFMPEG, "-y", "-hide_banner", "-loglevel", "error", *args],
                          capture_output=True, text=True, encoding="utf-8", errors="replace",
                          **_pu.SUBPROCESS_FLAGS)
    if proc.returncode != 0:
        raise RuntimeError(f"ffmpeg failed: {proc.stderr[-600:]}")


def generate_music_beds(out_dir: Path | None = None, *, duration_s: float = BED_DURATION_S,
                        force: bool = False) -> list[MusicBed]:
    """Write the four beds + sidecars into `out_dir` (default presets/music).

    Deterministic: lavfi synthesis, then a measured gain (ebur128 → `volume`)
    to land on −18 LUFS. Two passes rather than `loudnorm` because loudnorm's
    dynamic mode reshapes transients and would smear the kick grid the
    sidecar promises is exact. Existing files are kept unless `force`.
    """
    d = Path(out_dir) if out_dir is not None else music_dir()
    d.mkdir(parents=True, exist_ok=True)
    made: list[MusicBed] = []
    for name, bpm, mood in BED_SPECS:
        wav = d / f"{name}.wav"
        sidecar = d / f"{name}.json"
        if wav.exists() and sidecar.exists() and not force:
            made.extend(b for b in music_beds(d) if b.name == name)
            continue
        raw = d / f"{name}.raw.wav"
        expr = _bed_expression(bpm, mood)
        _run_ffmpeg(["-f", "lavfi", "-i", f"aevalsrc='{expr}':s={BED_SAMPLE_RATE}:d={duration_s:.3f}",
                     "-ac", "1", "-c:a", "pcm_s16le", str(raw)])
        gain = BED_TARGET_LUFS - _measure_lufs(raw)
        _run_ffmpeg(["-i", str(raw), "-af", f"volume={gain:.3f}dB",
                     "-ac", "2", "-ar", str(BED_SAMPLE_RATE), "-c:a", "pcm_s16le", str(wav)])
        raw.unlink(missing_ok=True)
        sidecar.write_text(json.dumps({
            "bpm": bpm, "mood": mood, "source": "procedural", "beat_grid_offset": 0.0,
            "duration_s": duration_s, "lufs": BED_TARGET_LUFS, "sample_rate": BED_SAMPLE_RATE,
        }, indent=2), encoding="utf-8")
        made.append(MusicBed(name=name, path=wav.resolve(), bpm=bpm, mood=mood,
                             duration_s=duration_s))
    return made


