TextAnchor = Literal["caption", "lower_third", "hook", "top", "center", "upper_third"]
TEXT_ANCHORS: tuple[str, ...] = ("caption", "lower_third", "hook", "top", "center", "upper_third")


@dataclass(frozen=True)
class TextStylePreset:
    name: str
    role: str
    font: str
    anchor: str
    size: float | None = None
    color: str | None = None
    stroke: str | None = None
    stroke_w: float | None = None
    upper: bool | None = None
    anim_in: str | None = None
    anim_out: str | None = None
    description: str = ""

    def y_frac(self, aspect: str) -> float:
        """Anchor → fraction for THIS canvas, from SAFE_ZONES."""
        z = safe_zone_for(aspect)
        return {
            "caption": z.caption_y,
            "lower_third": z.lower_third_y,
            "hook": 0.5,
            "center": 0.5,
            "top": z.y_min + 0.05,
            "upper_third": max(z.y_min, 0.30),
        }[self.anchor]

    def add_text_args(self, *, text: str, start: float, end: float,
                      canvas_w: int, canvas_h: int, aspect: str) -> dict[str, Any]:
        """Exact `add_text` args for this look on a canvas. Only advertised
        keys, so the result passes `validate_plan` unchanged."""
        args: dict[str, Any] = {
            "text": text, "start": start, "end": end, "role": self.role,
            "font": self.font, "x": canvas_w / 2, "y": round(canvas_h * self.y_frac(aspect), 1),
        }
        for key in ("size", "color", "stroke", "stroke_w", "upper", "anim_in", "anim_out"):
            v = getattr(self, key)
            if v is not None:
                args[key] = v
        return args


_TEXT_ROLES = ("super", "hook", "lower_third", "caption", "label", "watermark", "default")
_ANIMS = ("pop", "fade", "slide_up", "slide_down")


def text_styles() -> dict[str, TextStylePreset]:
    """Every `presets/text_styles/*.json`, validated: role, anchor, anim names
    and the font (must be a bundled file — a preset naming a font that is not
    shipped would render in Inter-Bold silently, see `text_overlay._font_path`)."""
    fonts = font_names()
    out: dict[str, TextStylePreset] = {}
    for stem, data in _read_json_files("text_styles").items():
        role = str(data.get("role", "default"))
        if role not in _TEXT_ROLES:
            raise ValueError(f"text style {stem}: role {role!r} not in {_TEXT_ROLES}")
        anchor = str(data.get("anchor", "center"))
        if anchor not in TEXT_ANCHORS:
            raise ValueError(f"text style {stem}: anchor {anchor!r} not in {TEXT_ANCHORS}")
        font = str(data.get("font", "Inter-Bold.ttf"))
        if fonts and font not in fonts:
            raise ValueError(f"text style {stem}: font {font!r} is not a bundled font")
        for key in ("anim_in", "anim_out"):
            if data.get(key) is not None and data[key] not in _ANIMS:
                raise ValueError(f"text style {stem}: {key} {data[key]!r} not in {_ANIMS}")
        out[stem] = TextStylePreset(
            name=stem, role=role, font=font, anchor=anchor,
            size=float(data["size"]) if data.get("size") is not None else None,
            color=data.get("color"), stroke=data.get("stroke"),
            stroke_w=float(data["stroke_w"]) if data.get("stroke_w") is not None else None,
            upper=data.get("upper"), anim_in=data.get("anim_in"), anim_out=data.get("anim_out"),
            description=str(data.get("description", "")),
        )
    return out


