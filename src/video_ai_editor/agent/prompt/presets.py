# 2. Paths
# --------------------------------------------------------------------------

def presets_dir() -> Path:
    """Read on every call so tests (and `desktop.py` under a custom WORKDIR)
    can monkeypatch `config.PRESETS_DIR` after import."""
    return Path(config.PRESETS_DIR)


def music_dir() -> Path:
    return presets_dir() / "music"


def _read_json_files(sub: str) -> dict[str, dict[str, Any]]:
    d = presets_dir() / sub
    if not d.is_dir():
        return {}
    out: dict[str, dict[str, Any]] = {}
    for p in sorted(d.glob("*.json")):
        try:
            data = json.loads(p.read_text(encoding="utf-8"))
        except (OSError, ValueError) as e:
            raise ValueError(f"preset {p} is not valid JSON: {e}") from e
        if not isinstance(data, dict):
            raise ValueError(f"preset {p} must be a JSON object")
        out[p.stem] = data
    return out


