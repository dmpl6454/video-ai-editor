@dataclass(frozen=True)
class TransitionLook:
    name: str
    types: tuple[str, ...]
    duration: float
    description: str = ""

    def type_at(self, i: int) -> str:
        return self.types[i % len(self.types)]


#: A stale `presets/transitions/<this>.json` from 0.7.0-pre is skipped by the
#: look loader; the catalog itself is `render.transitions.entries()` now.
TRANSITION_CATALOG_STEM = "catalog"


def transition_looks() -> dict[str, TransitionLook]:
    from ...render.transitions import all_names
    valid = set(all_names())
    out: dict[str, TransitionLook] = {}
    for stem, data in _read_json_files("transitions").items():
        if stem == TRANSITION_CATALOG_STEM:
            continue
        types = tuple(str(t) for t in (data.get("types") or []))
        if not types:
            raise ValueError(f"transition look {stem}: no types")
        bad = [t for t in types if t not in valid]
        if bad:
            raise ValueError(f"transition look {stem}: unknown transition types {bad}")
        duration = float(data.get("duration", 0.4))
        if not 0.1 <= duration <= 2.0:
            raise ValueError(f"transition look {stem}: duration {duration} outside [0.1, 2]")
        out[stem] = TransitionLook(name=stem, types=types, duration=duration,
                                   description=str(data.get("description", "")))
    return out


#: Category ids and labels, in the order the Transitions panel shows them.
#: Ids are stable (the JSON, the UI tabs and the benchmark name them);
#: labels are what a user reads.
TRANSITION_CATEGORIES: tuple[tuple[str, str], ...] = (
    ("basic", "Basic"), ("light", "Light"), ("wipe", "Wipe"), ("slide", "Slide"),
    ("zoom", "Zoom"), ("blur", "Blur"), ("shape", "Shape"), ("stylised", "Glitch & Stylised"),
)
TRANSITION_CATEGORY_IDS: tuple[str, ...] = tuple(i for i, _ in TRANSITION_CATEGORIES)
TRANSITION_DURATION_RANGE = (0.1, 2.0)
DEFAULT_TRANSITION_DURATION = 0.5


@dataclass(frozen=True)
class TransitionEntry:
    """One renderable look as the product shows it."""
    name: str            # the canonical render/transitions name
    label: str           # "Fade to Black"
    category: str        # one of TRANSITION_CATEGORY_IDS
    duration: float      # default seconds
    description: str = ""

    def as_dict(self) -> dict[str, Any]:
        return {"name": self.name, "label": self.label, "category": self.category,
                "duration": self.duration, "description": self.description}


#: Product family (render.transitions.FAMILY_NAMES) → the stable category id
#: the panel tabs, the benchmark and the recipe cards use.
_FAMILY_TO_CATEGORY: dict[str, str] = {
    "Basic": "basic", "Light": "light", "Wipe": "wipe", "Slide": "slide", "Zoom": "zoom",
    "Blur": "blur", "Shape": "shape", "Glitch/Stylised": "stylised",
}


def transition_catalog() -> dict[str, TransitionEntry]:
    """Every distinct look `render/transitions.py` can render, as the product
    shows it — a thin view over `render.transitions.entries()`: label =
    `display_name`, category = the look's family, duration =
    `default_duration`, description = `DESCRIPTIONS`.

    ONE source on purpose. A second catalog (presets/transitions/catalog.json)
    used to carry its own labels, families and durations and disagreed with
    the renderer on 45 of 72 rows, so a tile click and the same tile's
    "Every cut · via Prompt" applied different durations, the run log named
    "Push Left" for a "Slide Left" click, and 19 display names resolved to the
    wrong look through the grammar. Raises when the renderer's table is
    inconsistent (a look without a family or description) — never a silent
    `{}` that reads as "no transitions installed"."""
    from ...render.transitions import CUSTOM_EXPRS, NATIVE, entries
    looks = set(NATIVE) | set(CUSTOM_EXPRS)
    out: dict[str, TransitionEntry] = {}
    lo, hi = TRANSITION_DURATION_RANGE
    for e in entries():
        name = str(e["name"])
        category = _FAMILY_TO_CATEGORY.get(str(e["family"]), "")
        if category not in TRANSITION_CATEGORY_IDS:
            raise ValueError(f"transition catalog: {name} family {e['family']!r} has no category id")
        label = str(e["display"]).strip()
        if not label:
            raise ValueError(f"transition catalog: {name} has no display name")
        duration = float(e["default_duration"])
        if not lo <= duration <= hi:
            raise ValueError(f"transition catalog: {name} duration {duration} outside {TRANSITION_DURATION_RANGE}")
        description = str(e.get("description") or "").strip()
        if not description:
            raise ValueError(f"transition catalog: {name} has no description (render.transitions.DESCRIPTIONS)")
        out[name] = TransitionEntry(name=name, label=label, category=category, duration=duration,
                                    description=description)
    missing = sorted(looks - set(out))
    if missing:
        raise ValueError(f"transition catalog has no entry for renderable looks: {missing}")
    return out


def transition_entry(name: str) -> TransitionEntry | None:
    """The catalog entry for ANY accepted name — aliases (`zoom`, `whippan`,
    `crossdissolve`) resolve to their canonical look. None for unknown."""
    from ...render.transitions import canonical, is_valid
    if not is_valid(name):
        return None
    return transition_catalog().get(canonical(name))


def transition_default_duration(name: str, fallback: float = DEFAULT_TRANSITION_DURATION) -> float:
    """Per-transition default seconds (a whip is 0.25, a fade to black 0.6).
    The compositor and the Transitions panel read this; `fallback` for a
    name outside the catalog."""
    entry = transition_entry(name)
    return entry.duration if entry is not None else fallback


def transitions_by_category() -> dict[str, list[TransitionEntry]]:
    """Category id → entries, categories in panel order, entries by label."""
    cat = transition_catalog()
    out: dict[str, list[TransitionEntry]] = {cid: [] for cid in TRANSITION_CATEGORY_IDS}
    for entry in sorted(cat.values(), key=lambda e: e.label):
        out[entry.category].append(entry)
    return out


