"""Presets the planner composes from, and the safe zones the verifier measures
against (spec §2.8).

Four preset families live under `config.PRESETS_DIR`; three are JSON the repo
ships and one is generated:

  text_styles/*.json   named looks for `add_text` — role, font, size, anim,
                       and an ANCHOR name instead of a y fraction, so the
                       fraction always comes from SAFE_ZONES for the canvas
                       the text lands on (a 9:16 caption sits at 0.76, a
                       16:9 one at 0.85; a hard-coded number would be wrong
                       on one of them).
  transitions/*.json   named looks for `add_transition` — a cycle of types
                       and one duration; every type is validated against
                       `render.transitions.all_names()` at load, so a typo
                       fails here and never reaches a plan.
  (no catalog file)    the CapCut-style product surface — display name,
                       family, default duration and one line per distinct
                       look — is `render.transitions.entries()`;
                       `transition_catalog()` is a typed view over it. A
                       second hand-written copy used to live here and
                       disagreed with the renderer on 45 of 72 rows.
  templates/*.json     named whole-edit recipes (`auto_edit` variants) —
                       ordered `{recipe, slots}` entries plus the keywords the
                       grammar matches. Stage order comes from the recipe
                       table, never from the file.
  music/*.wav + .json  procedural beds, GENERATED by `generate_music_beds`
                       (CLI: scripts/gen_music_beds.py) and gitignored. The
                       sidecar carries the exact kick grid (`bpm`,
                       `beat_grid_offset`), so the beat_sync recipe needs no
                       beat detector for a preset bed.

WHY `SAFE_ZONES` lives here and is imported by the verifier AND the §4.9
handler defaults: TikTok/Reels chrome covers the bottom ~20% and the right
rail of a 9:16 frame, and the renderer anchored captions at
`canvas_h − 0.16·h` = 0.84 — inside the covered band. Rather than loosen the
check, the product defaults move up on vertical canvases; both sides read
the same table so they cannot disagree about where "safe" is.

WHY the loaders never raise on a missing directory: the packaged app ships
`presets/` via `--add-data`, but the music beds are generated at build time
and a source checkout that skipped the script has none. `music_beds()`
returns `[]` and the `music` recipe asks for an upload instead — degrade
honestly rather than 500 on "add music".
"""
